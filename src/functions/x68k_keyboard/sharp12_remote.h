// ===================================================================================
// sharp12_remote.h
// ===================================================================================
// X68000 キーボードの REMOTE 端子 (mini-DIN pin 6) から SHARP 12-bit リモコン
// コードを送出する。CH32X035 の PB8 に直結。
//
// SHARP12 フォーマット (ベースバンド / アクティブ Low):
//   データ 0  : LOW 320us → HIGH 680us
//   データ 1  : LOW 320us → HIGH 1680us
//   トレーラー: LOW 320us → HIGH (残り、約 50ms-(data 部) になるよう可変)
//   1 パケット = 12 bit データ部 + トレーラー = 50ms
//   1 リクエスト = データ + 反転データ = 100ms
//
// アイドル時の PB8 は HIGH。
// ===================================================================================
#ifndef _SHARP12_REMOTE_H
#define _SHARP12_REMOTE_H

#include <stdint.h>

void sharp12_remote_init(void);

/**
 * 1 リクエスト分 (データ + 反転データ) を送出する。約 100ms ブロックする。
 *
 * @param code 0x01-0x1F の制御コード。範囲外でも送出はするが意味のあるコード
 *             だけ呼び出すこと。値検証は呼び出し側で行う前提。
 */
void sharp12_remote_emit(uint8_t code);

#endif
