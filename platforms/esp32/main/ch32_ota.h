// ===================================================================================
// ch32_ota.h  (ESP32 / CH32 ファーム自動更新オーケストレーション)
// ===================================================================================
// 起動時に接続中の CH32 を IDENTIFY で識別し (variant + version)、ESP32 内蔵の
// 対応イメージの方が新しければ SWD で自動書き換えする。app/配信は不要。
//
// 流れ: IDENTIFY(I2C) → 版判定 → 古ければ [ENTER_SWD(I2C) → I2C teardown →
//        ch32_swd_flash → reboot → I2C ブリッジ復帰]。
// ===================================================================================
#pragma once

#include <stdint.h>

// 起動時に 1 回呼ぶ (i2c_bridge_init の後)。更新した場合は内部で I2C ブリッジを
// 再 init して戻る (rx_cb は復帰後のブリッジに再登録するコールバック)。
void ch32_ota_check_and_update(void (*rx_cb)(const uint8_t* midi, int len));
